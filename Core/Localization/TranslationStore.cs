// ─── Hanna Lab string catalogue ────────────────────────────────────────────────
//
// SINGLE POINT OF TRUTH for every user-facing string in the app.
//
// Naming convention (see NAMING.md):
//
//   <Section>_<Element>[_<Variant>]
//
//   • Section is the screen / feature area (Pascal-cased, no abbreviations):
//       AppShell, Flyout, Home, Device, Measure, Halo, Photometer, Multimeter,
//       LogHistory, Settings, Cloud, Profile, Register, Theme, Instrument,
//       Common
//   • Element is the role (Title, Subtitle, Hint, Button, Label, Placeholder,
//       Message, Error, Empty, Section, Confirm).
//   • Variant disambiguates multi-state strings (Active / Paused, On / Off).
//
//   Examples:
//       AppShell_Title_Home, AppShell_Title_Measure
//       Flyout_Login, Flyout_Logout
//       Halo_Calibration_Title, Halo_Calibration_Subtitle
//       Common_Cancel, Common_OK, Common_Delete
//
// Adding a new string:
//   1. Pick a section + element from the list above. If none fits, extend the
//      list (and keep NAMING.md in sync).
//   2. Add the English value in En(). All other languages fall back to English
//      until a translation is added.
//   3. Use the new key via LocalizedViewModelBase.Loc.T("Key") or
//      LocalizationService.T("Key"). NEVER add literal English to a view.
//
// ──────────────────────────────────────────────────────────────────────────────

